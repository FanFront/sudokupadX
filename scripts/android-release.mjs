// Configure reproducible, test-only Android release builds without CI secrets.
// The repository-bundled keystore is PUBLIC: never use it for production.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const BASE_VERSION_CODE = 2_000_000;
export const TEST_KEYSTORE_SHA256 = 'd1d17837401b791625ee288e6c87884d9a4ede92e234603fcdb508394b0e3240';
export const TEST_CERT_SHA256 = '8c7c54f2b981c9f3b8ee56cc061afe8e5ac2022fa38e24ae21cf367213665f7f';
export const SIGNING_MARKER = '// Sudokupadx: permanent public test signing + release shrinking (managed by scripts/android-release.mjs)';
const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function calculateVersionCode(runNumber, explicitCode) {
  if (explicitCode !== undefined && explicitCode !== null && explicitCode !== '') {
    const code = Number(explicitCode);
    if (!Number.isSafeInteger(code) || code < BASE_VERSION_CODE || code > 2_100_000_000) {
      throw new Error('SUDOKUPADX_VERSION_CODE must be an integer between 2000000 and 2100000000');
    }
    return code;
  }
  if (runNumber === undefined || runNumber === null || runNumber === '') return BASE_VERSION_CODE;
  const value = Number(runNumber);
  if (!Number.isSafeInteger(value) || value < 1 || BASE_VERSION_CODE + value > 2_100_000_000) {
    throw new Error('GITHUB_RUN_NUMBER is not a valid increasing Android version-code suffix');
  }
  return BASE_VERSION_CODE + value;
}

export function applyGradleSigning(gradle) {
  if (!gradle.includes('id("com.android.application")')) {
    throw new Error('Expected Tauri app/build.gradle.kts (Android application), not a library');
  }
  if (gradle.includes(SIGNING_MARKER)) return gradle;
  return gradle.trimEnd() + `
    
${SIGNING_MARKER}
// This file is regenerated by tauri android init. Run the setup script after
// generating the Android project and before calling tauri android build.
android {
    signingConfigs {
        create("sudokupadxPermanentTest") {
            // rootProject is src-tauri/gen/android.
            storeFile = rootProject.file("../../../android-signing/test-signing.p12")
            storePassword = "SudokuPadX-Test-2026"
            keyAlias = "sudokupadx-test"
            keyPassword = "SudokuPadX-Test-2026"
        }
    }
    buildTypes {
        getByName("release") {
            signingConfig = signingConfigs.getByName("sudokupadxPermanentTest")
            // R8 minifies Java/Kotlin and the Android resource shrinker
            // discards assets not referenced by the native Android shell.
            isMinifyEnabled = true
            isShrinkResources = true
        }
    }
}
`;
}

export function prepareVersionCode(root = REPO, env = process.env) {
  const file = path.join(root, 'src-tauri', 'tauri.conf.json');
  const conf = JSON.parse(fs.readFileSync(file, 'utf8'));
  const versionCode = calculateVersionCode(env.GITHUB_RUN_NUMBER, env.SUDOKUPADX_VERSION_CODE);
  if (conf.identifier !== 'com.fanfront.sudokupadx') {
    throw new Error('Unexpected Android application id; this may break upgrades');
  }
  conf.bundle ??= {};
  conf.bundle.android ??= {};
  conf.bundle.android.versionCode = versionCode;
  fs.writeFileSync(file, JSON.stringify(conf, null, 2) + '\n');
  console.log('SudokuPad X Android versionCode: ' + versionCode);
  return versionCode;
}

export function prepareSigning(root = REPO) {
  const keyFile = path.join(root, 'android-signing', 'test-signing.p12');
  const digest = createHash('sha256').update(fs.readFileSync(keyFile)).digest('hex');
  if (digest !== TEST_KEYSTORE_SHA256) {
    throw new Error('Bundled test keystore has changed; upgrades would lose their signature');
  }
  const gradleFile = path.join(root, 'src-tauri', 'gen', 'android', 'app', 'build.gradle.kts');
  const source = fs.readFileSync(gradleFile, 'utf8');
  fs.writeFileSync(gradleFile, applyGradleSigning(source));
  console.log('Configured stable release key (test ONLY), R8 and resource shrinking.');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const action = process.argv[2];
  try {
    if (action === 'version') prepareVersionCode();
    else if (action === 'sign') prepareSigning();
    else throw new Error('Usage: node scripts/android-release.mjs version|sign');
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
